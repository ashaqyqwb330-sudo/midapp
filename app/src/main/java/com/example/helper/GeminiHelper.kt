    suspend fun askGemini(prompt: String): String = withContext(Dispatchers.IO) {
        val trimmed = prompt.trim()
        
        // 1. Precise exact offline fallback check
        if (offlineKnowledgeBase.containsKey(trimmed)) {
            return@withContext offlineKnowledgeBase[trimmed]!!
        }

        // 2. Obtain BuildConfig API key dynamically and safely
        var apiKey = ""
        try {
            apiKey = com.example.BuildConfig.GEMINI_API_KEY
        } catch (e: Exception) {
            e.printStackTrace()
        }

        if (apiKey.isBlank() || apiKey == "YOUR_GEMINI_API_KEY_HERE" || apiKey.contains("placeholder", ignoreCase = true)) {
            // No valid API key -> utilize our semantic keyword parser offline local engine
            return@withContext matchKeywordOffline(trimmed)
        }

        // 3. Make the online REST request to API
        try {
            val jsonPayload = JSONObject().apply {
                put("contents", JSONArray().apply {
                    put(JSONObject().apply {
                        put("parts", JSONArray().apply {
                            put(JSONObject().apply {
                                put("text", """
                                    أنت طبيب خبير ومهندس إكلينيكي عسكري مساعد بالخدمات الطبية العسكرية.
                                    مهمتك الإجابة عن التساؤلات الطبية والتشغيلية والهندسية للطلاب باللغة العربية بدقة وموضوعية.
                                    التزم بالإجابة من واقع المناهج والمراجع الطبية وصيانة الأجهزة الطبية.
                                    السؤال هو: $trimmed
                                """.trimIndent())
                            })
                        })
                    })
                })
            }

            val client = OkHttpClient.Builder()
                .connectTimeout(30, java.util.concurrent.TimeUnit.SECONDS)
                .readTimeout(30, java.util.concurrent.TimeUnit.SECONDS)
                .build()

            val request = Request.Builder()
                .url("$BASE_URL?key=$apiKey")
                .post(jsonPayload.toString().toRequestBody("application/json".toMediaType()))
                .build()

            client.newCall(request).execute().use { response ->
                if (response.isSuccessful) {
                    val bodyString = response.body?.string()
                    if (bodyString != null) {
                        val jsonObj = JSONObject(bodyString)
                        val textAnswer = jsonObj.getJSONArray("candidates")
                            .getJSONObject(0)
                            .getJSONObject("content")
                            .getJSONArray("parts")
                            .getJSONObject(0)
                            .getString("text")
                        return@withContext textAnswer
                    }
                }
                return@withContext matchKeywordOffline(trimmed) + "\n\n*(تنويه: حدثت مشكلة في الاتصال بالخادم، تم جلب الإجابة المسندة محلياً)*"
            }
        } catch (e: Exception) {
            e.printStackTrace()
            return@withContext matchKeywordOffline(trimmed) + "\n\n*(تنويه: تعمل حالياً في وضع عدم الاتصال بالإنترنت - وتم جلب هذا الرد الفوري من قاعدة البيانات الميدانية المحلية)*"
        }
    }

    private fun matchKeywordOffline(prompt: String): String {
        for (item in keywordsDatabase) {
            val keywords = item.first
            val ans = item.second
            for (key in keywords) {
                if (prompt.contains(key, ignoreCase = true)) {
                    return ans
                }
            }
        }

        return """
            📚 **الرد الاسترشادي المعتمد من المناهج الطبية:**
            
            نشكر تساؤلك الفذ. لم يتم العثور على مطابقة لفظية دقيقة ضمن العناوين المخصصة، ولكننا نوصيك بزيارة **الدليل الطبي المنظم** بقيمة **مناهج وأدلة الكتب بالفصل المناسب**.
            
            **إرشادات للمراجعة السريعة:**
            • لفحص الأجهزة ومعايرتها: يمكنك الاطلاع على الفصل الخامس والفصل السادس (أجهزة المستشفى).
            • للاطلاع على تدريبات الميدان: ننصحك بالفصل العاشر وفحص "المهارات السريرية" المدرجة بالصفحة الرئيسية للتطبيق.
            • للقياسات الحيوية: استخدم **📊 حاسبات اللوحة** لحساب الوعي ومؤشر الكلى وغازات الدم ABG فوراً.
            
            *ملاحظة: يمكنك إعداد مفتاح API الخاص بجيميني في إعدادات التطبيق لتمكين الاستجابة الذكية الموسعة في أي وقت.*
        """.trimIndent()
    }
