def main():
    if not BACKUP.exists():
        print(f"❌ النسخة الاحتياطية غير موجودة: {BACKUP}")
        return

    print(f"🔍 البحث العميق في {BACKUP} ...")
    moved = 0

    # البحث عن جميع ملفات PDF في النسخة الاحتياطية
    for old_file in BACKUP.rglob("*.pdf"):
        # تجاهل ملفات الغلاف (قد تكون بجانبها)
        if "غلاف" in old_file.name:
            continue
        
        old_name = old_file.name
        if old_name in OLD_TO_NEW:
            target_dir, new_name = OLD_TO_NEW[old_name]
            dst_path = DATA_DIR / target_dir / new_name
            dst_path.parent.mkdir(parents=True, exist_ok=True)

            # لا نستبدل إذا كان الهدف موجوداً بحجم معقول (حقيقي)
            if dst_path.exists() and dst_path.stat().st_size > 10240:
                print(f"⏩ تخطي (موجود): {new_name}")
                continue

            try:
                shutil.copy2(str(old_file), str(dst_path))
                print(f"✅ {old_name} -> {target_dir}/{new_name}")
                moved += 1
            except Exception as e:
                print(f"❌ فشل {old_name}: {e}")

    print(f"\n🎉 تم نقل {moved} كتاب حقيقي.")

    if moved > 0:
        print("➡️ الآن قم بتشغيل: python rebuild_json.py")

if __name__ == "__main__":
    main()
